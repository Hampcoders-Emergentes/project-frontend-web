#!/usr/bin/env node
/**
 * Writes `src/environments/environment.generated.ts`, the production configuration used by
 * `ng build` (see `fileReplacements` in angular.json). The API origin is a build-time value because
 * Angular bakes environment files into the bundle.
 *
 * Inputs:
 *   API_ORIGIN                          origin only, e.g. https://api.example.com (no path)
 *   VERCEL=1 | ELECTROLINK_REQUIRE_API_ORIGIN=true
 *                                       fail instead of falling back to localhost when API_ORIGIN is unset
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const LOCAL_FALLBACK_ORIGIN = 'http://localhost:8080';
const LOCAL_HOSTS = new Set(['localhost', '127.0.0.1']);

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'src/environments/environment.generated.ts');

function parseApiOrigin(value) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`API_ORIGIN is not a valid absolute URL: "${value}"`);
  }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') {
    throw new Error(`API_ORIGIN must use http or https: "${value}"`);
  }
  if (url.pathname !== '/' || url.search || url.hash || url.username || url.password) {
    throw new Error(`API_ORIGIN must be an origin only (scheme, host, optional port): "${value}"`);
  }
  if (url.protocol === 'http:' && !LOCAL_HOSTS.has(url.hostname)) {
    throw new Error(`API_ORIGIN must use https outside localhost: "${value}"`);
  }
  return url.origin;
}

const requireOrigin = process.env.VERCEL === '1' || process.env.ELECTROLINK_REQUIRE_API_ORIGIN === 'true';
const rawOrigin = process.env.API_ORIGIN?.trim() ?? '';

let apiOrigin;
if (rawOrigin === '') {
  if (requireOrigin) {
    throw new Error('API_ORIGIN is required for this build (set it in the Vercel environment or as a build arg).');
  }
  console.warn(`[environment] API_ORIGIN not set; using ${LOCAL_FALLBACK_ORIGIN} for the production build.`);
  apiOrigin = LOCAL_FALLBACK_ORIGIN;
} else {
  apiOrigin = parseApiOrigin(rawOrigin);
}

const source = `// Generated by scripts/generate-environment.mjs from API_ORIGIN. Do not edit; git-ignored.
export const environment = {
  production: true,
  apiOrigin: ${JSON.stringify(apiOrigin)},
};
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, source, 'utf8');
console.log(`[environment] production apiOrigin: ${apiOrigin}`);
